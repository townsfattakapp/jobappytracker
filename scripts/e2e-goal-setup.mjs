import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch()
try {
  for (const mode of ['roadmap', 'manual', 'start']) {
    const page = await browser.newPage({ viewport: mode === 'manual' ? { width: 390, height: 844 } : { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://localhost:3000/app')
    await page.getByRole('button', { name: 'Continue offline (local only)' }).click()
    await page.getByRole('button', { name: 'Create your goal', exact: true }).click()
    await page.getByRole('heading', { name: 'Build your learning plan', exact: true }).waitFor()
    await page.getByLabel('Goal setup steps').waitFor()
    assert.equal(await page.getByLabel('Goal setup steps').locator('li').count(), 4)
    await page.getByRole('radio', { name: /Learn a programming language/ }).click()
    await page.getByRole('button', { name: 'Choose a starting point', exact: true }).click()
    await page.getByLabel('Find a path or skill').fill('no-matching-skill')
    await page.getByText(/No matches. Try a broader search/).waitFor()
    await page.getByLabel('Find a path or skill').fill('Python')
    await page.locator('button[aria-pressed]').filter({ hasText: 'Python' }).first().click()
    await page.getByRole('button', { name: 'Customize my plan', exact: true }).click()
    await page.getByLabel('Goal name', { exact: true }).fill(`Learning flow ${mode}`)
    assert.equal(await page.getByLabel('Goal description').isVisible(), false)
    await page.getByText('More preferences', { exact: false }).click()
    await page.getByLabel('Goal description').fill('A learner-friendly plan')
    const next = page.getByRole('button', { name: 'Review my plan', exact: true })
    for (const day of ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']) await page.getByRole('button', { name: day, exact: true }).click()
    assert.equal(await next.isDisabled(), true)
    await page.getByRole('button', { name: 'Mon', exact: true }).click()
    await page.getByLabel('Start date', { exact: true }).fill('')
    assert.equal(await next.isDisabled(), true)
    await page.getByLabel('Start date', { exact: true }).fill('2026-10-01')
    await page.getByRole('radio', { name: /^Target date/ }).click()
    await page.getByLabel('Target date', { exact: true }).fill('2026-09-01')
    assert.equal(await next.isDisabled(), true)
    await page.getByRole('radio', { name: /^Estimate my finish date/ }).click()
    await page.getByRole('button', { name: 'Tue', exact: true }).click()
    await page.getByRole('button', { name: 'Wed', exact: true }).click()
    await next.click()
    await page.getByRole('heading', { name: 'Your plan, ready to start', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Edit topics or schedule' }).click()
    assert.equal(await page.getByLabel('Goal name', { exact: true }).inputValue(), `Learning flow ${mode}`)
    await next.click()
    await page.locator(`input[name="goal-start-mode"][value="${mode}"]`).check()
    await page.getByRole('button', { name: 'Create my learning plan', exact: true }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    if (mode === 'manual') await page.screenshot({ path: 'e2e-goal-setup-mobile.png', fullPage: true })
    await page.getByRole('button', { name: 'Create my learning plan', exact: true }).click()
    await page.getByRole('heading', { name: 'Build your learning plan', exact: true }).waitFor({ state: 'hidden' })
    await page.waitForFunction(name => JSON.parse(localStorage.getItem('job-app-tracker-v2') || '{}').goals?.some(goal => goal.name === name), `Learning flow ${mode}`)
    const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('job-app-tracker-v2')))
    const saved = stored.goals.find(goal => goal.name === `Learning flow ${mode}`)
    assert.equal(saved.description, 'A learner-friendly plan')
    assert.equal(saved.tracks.length, 1)
    assert.equal(stored.roadmap.some(day => day.goalId === saved.id), mode === 'roadmap')
    assert.deepEqual(errors, [])
    await page.close()
  }
  console.log('Goal setup passed: four steps, search, optional fields, schedule validation, back/edit, mobile layout, and all three save modes.')
} finally {
  await browser.close()
}
