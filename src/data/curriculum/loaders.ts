export async function loadLibraryTrack(trackId: string): Promise<CurriculumTrack | null> {
  const loader = libraryLoaders[trackId]
  if (!loader) return null
  try {
    const mod = await loader()
    for (const key of Object.keys(mod)) {
      const val = mod[key]
      if (val && typeof val === 'object' && val.id === trackId) return val as CurriculumTrack
    }
    if (mod.default && typeof mod.default === 'object' && mod.default.id === trackId) return mod.default as CurriculumTrack
  } catch (err) {
    console.error(`Failed to dynamically load curriculum track ${trackId}:`, err)
  }
  return null
}
